const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const src=fs.readFileSync(path.join(__dirname,'../app/src/main/assets/auto-gps.js'),'utf8');
const context={};vm.runInNewContext(src,context,{filename:'auto-gps.js'});
const {createTracker,distance}=context.SRGAutoGPS;
const p=(x=0)=>({lat:50.0,lon:21+x/71000,gpsRadius:50,name:'test '+x});
const stops=[p(0),p(500),p(1000)];
const fix=(x,acc=43)=>({...p(x),acc});
const tracker=createTracker();
const tick=(f,now,index=0,opts={})=>tracker.evaluate({enabled:true,courseActive:true,stops,index,pending:null,now,fix:f,...opts});
assert.ok(distance(stops[0],stops[1])>300);
assert.equal(tick(fix(500),0,0,{courseActive:false}).advance,undefined,'inactive course');
assert.equal(tick(null,0).advance,undefined,'no GPS');
for(let t=0;t<10;t++)assert.equal(tick(fix(500,120),t*1000).advance,undefined,'poor accuracy');
assert.equal(tick(fix(100),20000).advance,undefined,'too far');
assert.equal(tick(fix(499),21000).advance,undefined,'first fix');
assert.equal(tick(fix(500),22100).advance,undefined,'second fix');
assert.equal(tick(fix(501),23200).advance,true,'third fix + 2.2s -> next stop');
assert.equal(tick(fix(1000),24000,1).advance,undefined,'cooldown prevents jump');
assert.equal(tick(fix(500),29000,1).advance,undefined,'do not jump while still at current stop');
assert.equal(tick(fix(1000),30000,1).advance,undefined,'start next confirmation');
assert.equal(tick(fix(1000),31100,1).advance,undefined,'confirmation 2');
assert.equal(tick(fix(1000),32200,1).advance,true,'second stop eventually advanced');
assert.equal(tick(fix(1000),33000,2).advance,undefined,'last stop never auto-finishes');
tracker.reset();
assert.equal(tick(fix(500),40000,0,{pending:1}).advance,undefined,'manual preview');
assert.equal(tick(fix(500),42000,0,{enabled:false}).advance,undefined,'AUTO OFF');
// Candidate reset if signal is lost before 3 valid readings.
tracker.reset();
assert.equal(tick(fix(500),50000).advance,undefined);
assert.equal(tick(fix(500),51000).advance,undefined);
assert.equal(tick(fix(500,95),52000).advance,undefined);
assert.equal(tick(fix(500),53000).advance,undefined);
assert.equal(tick(fix(500),54100).advance,undefined);
assert.equal(tick(fix(500),55200).advance,true);
console.log('PASS 18 assertions: kolejność RJ, potwierdzenia, GPS, dokładność, ręczny, cooldown, koniec kursu');
