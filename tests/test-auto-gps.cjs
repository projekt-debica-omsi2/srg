const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'../app/src/main/assets/auto-gps.js'),'utf8');
const ctx={};vm.runInNewContext(src,ctx,{filename:'auto-gps.js'});
const {createTracker,distance}=ctx.SRGAutoGPS;
const p=(m,id)=>({lat:50,lon:21+m/71600,id,name:`Stop ${id}`});
const stops=[p(0,1),p(500,2),p(1000,3),p(1500,4)];
const fix=(m,speed=9,acc=43)=>({...p(m),speed,acc});
const run=(tracker,m,now,index=0,extra={})=>tracker.evaluate({enabled:true,courseActive:true,stops,index,courseKey:'rj:7',pending:null,now,fix:fix(m),...extra});
assert.ok(distance(stops[0],stops[1])>450);
let tr=createTracker();
assert.match(run(tr,0,1000).status,/OD/);
assert.equal(run(tr,25,2000).advance,undefined,'before 50m');
assert.equal(run(tr,56,3000).advance,undefined,'one GPS confirmation at departure');
const departure=run(tr,67,4100);assert.equal(departure.advance,true);assert.equal(departure.nextIndex,1);assert.equal(departure.departure,true);
assert.equal(run(tr,100,5100,1).advance,undefined,'no double jump');
assert.equal(run(tr,490,15000,1).advance,undefined,'arrival not advancement');
assert.equal(run(tr,500,16000,1,{fix:fix(500,0)}).advance,undefined,'stationary arrival');
assert.equal(run(tr,552,19000,1).advance,undefined,'one confirmation next departure');
assert.equal(run(tr,572,20200,1).nextIndex,2,'second departure advances again');
tr=createTracker();
run(tr,0,1000,0,{fix:fix(0,0)});
for(let i=0;i<5;i++)assert.equal(run(tr,65,2000+i*1100,0,{fix:fix(65,0)}).advance,undefined,'no stationary drift advance');
tr=createTracker();
run(tr,0,1000);
assert.equal(run(tr,-55,2100).advance,undefined,'reverse direction must not advance');
assert.equal(run(tr,-70,3200).advance,undefined,'still going backwards');
tr=createTracker();
run(tr,0,1000);
assert.equal(run(tr,58,2100,0,{fix:fix(58,10,120)}).advance,undefined,'inaccurate GPS cannot advance');
assert.equal(run(tr,67,3200).advance,undefined,'one valid fix is not enough after inaccurate fix');
assert.equal(run(tr,78,4400).advance,true,'two valid fixes');
tr=createTracker();
assert.equal(run(tr,80,1000).advance,undefined,'not start 80m from current stop');
assert.equal(run(tr,100,2100).advance,undefined,'must arm at current stop first');
tr=createTracker();
run(tr,0,1000);
assert.equal(run(tr,55,2100,0,{pending:2}).advance,undefined,'manual selection must block');
assert.equal(run(tr,65,3200,0,{enabled:false}).advance,undefined,'off must block');
tr=createTracker();
assert.equal(run(tr,1530,1000,3).advance,undefined,'terminal index remains terminal');
console.log('PASS departure progression: ~50m, motion, reverse, stationary, errors, single stop, manual/off, terminal');
