const assert=require('node:assert/strict'),fs=require('fs'),vm=require('vm');
const ctx={window:{}};vm.runInNewContext(fs.readFileSync('app/src/main/assets/rail-rzeszow-data.js','utf8'),ctx);
const feed=JSON.parse(JSON.stringify(ctx.window.SRGRailRzeszow)),t=require('../app/src/main/assets/transfers.js');
assert.equal(feed.departures.length,159);
assert.equal(new Set(feed.departures.map(r=>[r.time,r.carrier,r.direction].join('|'))).size,159);
assert.equal(feed.departures.filter(r=>r.carrier==='POLREGIO').length,112);
assert.equal(feed.departures.filter(r=>r.carrier==='PKP Intercity').length,45);
assert.equal(feed.departures.filter(r=>r.carrier==='RegioJet').length,2);
assert.equal(t.railRows({...feed,calendar:{mode:'pending'}},'2026-10-19','18:00').length,0);
for(const day of ['2026-10-19','2026-10-20','2026-10-21','2026-10-22','2026-10-23','2026-10-26'])assert.equal(t.railRows(feed,day,'06:00').length,8);
for(const day of ['2026-10-24','2026-10-25'])assert.equal(t.railRows(feed,day,'06:00').length,8);
const dated={...feed,calendar:{mode:'dates',dates:['2026-10-19']}};
const rows=t.railRows(dated,'2026-10-19','18:29');
assert.equal(rows.length,8);assert.equal(rows[0].time,'18:32');assert.equal(rows[7].time,'19:26');
assert.equal(t.railRows(dated,'2026-10-20','00:00').length,0);
assert.equal(t.railRows(dated,'2026-10-19','23:39').length,2);
assert.equal(t.railRows(dated,'2026-10-19','23:40').length,0);
assert.deepEqual(t.railRows(dated,'2026-10-19','04:54').slice(0,2).map(r=>r.direction),['Lublin Główny','Jasło']);
assert(!JSON.stringify(feed.departures).match(/"(bus|utrudnienia)"/i));
console.log('PASS rail: 159 verified rows, calendar guard, eight nearest, same-time departures, exact expiry');
