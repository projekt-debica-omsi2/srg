const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const load=f=>fs.readFileSync(path.join(__dirname,'../app/src/main/assets/',f),'utf8');
const ctx={};vm.runInNewContext(load('auto-gps.js'),ctx);vm.runInNewContext(load('voice-gps.js'),ctx);
const stops=[{id:1,name:'Pierwszy',lat:50,lon:21},{id:2,name:'Drugi',lat:50,lon:21+500/71600},{id:3,name:'Trzeci',lat:50,lon:21+1000/71600}];
const fix=(m,speed=8,acc=43)=>({lat:50,lon:21+m/71600,speed,acc});
const tr=ctx.SRGVoiceGPS.createTracker();
const e=(m,time,index=1,opts={})=>tr.evaluate({enabled:true,courseActive:true,courseKey:'c1',stops,index,pending:null,fix:fix(m),now:time,...opts});
assert.equal(e(0,1000,0).arrival,undefined,'initial direction announcement covers first stop');
assert.equal(e(65,1500,1).arrival,undefined,'cannot speak future stop at departure');
assert.equal(e(430,5000,1).arrival,undefined,'70m not yet arrived');
assert.equal(e(455,6000,1).arrival,undefined,'first arrival GPS fix');
const arrived=e(475,7200,1);assert.equal(arrived.arrival,true);assert.equal(arrived.stopId,2,'announce exact arrival stop');
assert.equal(e(500,8300,1).arrival,undefined,'no repeat on same stop');
assert.equal(e(550,9500,1).arrival,undefined,'departure from that stop does not repeat arrival');
assert.equal(e(950,14000,2).arrival,undefined,'first fix of third');
const third=e(975,15200,2);assert.equal(third.arrival,true);assert.equal(third.stopId,3);
tr.reset();
assert.equal(e(490,20000,1,{enabled:false}).arrival,undefined,'announcements off');
assert.equal(e(490,21000,1,{pending:2}).arrival,undefined,'manual selection blocks');
assert.equal(e(490,23000,1,{fix:fix(490,2,110)}).arrival,undefined,'low accuracy blocks');
console.log('PASS arrival voice: name only at target, 2 GPS fixes, first/last, once per stop, manual/off/poor GPS');
