'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const engine=require('../app/src/main/assets/schedule-deviation.js');
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
const manifest=fs.readFileSync('app/src/main/AndroidManifest.xml','utf8');
const build=fs.readFileSync('app/build.gradle','utf8');
const {calculate,estimateTimes,parseHHMM}=engine;
function at(year,month,day,h,m,s=0){return new Date(year,month-1,day,h,m,s)}
const base=at(2026,10,13,16,0).getTime();
function check(now,planned,expected,kind){const a=calculate({now,plannedTime:planned,startTime:'16:00',courseDepartureAt:base});assert.equal(a.text,expected,`time=${now}`);assert.equal(a.kind,kind);if(kind==='late')assert(a.text.startsWith('-'));if(kind==='early')assert(a.text.startsWith('+'));}
check(at(2026,10,13,16,0,0),'16:00','0:00','ontime');
check(at(2026,10,13,16,0,59),'16:00','-0:59','late');
check(at(2026,10,13,16,0,59),'16:02','+1:01','early');
check(at(2026,10,13,16,5,7),'16:02','-3:07','late');
check(at(2026,10,13,16,9),'16:09','0:00','ontime');
check(at(2026,10,13,16,38),'16:31','-7:00','late');
check(at(2026,10,13,17,15),'17:20','+5:00','early');
const unknown=calculate({now:at(2026,10,13,16,40),plannedTime:null,startTime:'16:00',courseDepartureAt:base});
assert.equal(unknown.text,'—');assert.equal(unknown.kind,'unknown');
assert.equal(calculate({now:at(2026,10,13,16,5),plannedTime:'--:--',startTime:'16:00',courseDepartureAt:base}).kind,'unknown');
const midnight=at(2026,10,13,23,55).getTime();
const m=calculate({now:at(2026,10,14,0,8),plannedTime:'00:05',startTime:'23:55',courseDepartureAt:midnight});
assert.equal(m.text,'-3:00');
const gps={'1':[50.0,21.0],'2':[50.0,21.003],'3':[50.0,21.017],'4':[50.0,21.040]};
const stops=[{id:1},{id:2},{id:3},{id:4}];
let times=estimateTimes({startTime:'16:00',endTime:'17:20',stops,positions:gps});
assert.equal(times[0],'16:00');assert.equal(times.at(-1),'17:20');
assert(times[1]<'16:20',`GPS-based should give shorter first section ${times[1]}`);
assert(times[2]>'16:20',`GPS-based should give more time on longer sections ${times[2]}`);
assert.equal(estimateTimes({startTime:'23:50',endTime:'00:10',stops:[{id:1},{id:2}],positions:{}}).at(-1),'00:10');
assert.deepEqual(estimateTimes({startTime:'16:00',endTime:'17:20',stops:[]}),[]);
assert.equal(parseHHMM('24:00'),null);
assert(html.includes('schedule-deviation.js'));
assert(html.includes('const info=plannedTimeInfo(idx,ss.length)'),'Delay must use currently confirmed stop');
assert(html.includes("$('#camDelay').textContent=delta.text"));
assert(html.includes("$('#courseDelay').textContent=delta.text"));
assert(html.includes("estimated:true"),'Mark estimated timetables');
assert(html.includes("if(c.photoTimesKey)"),'Keep true photographed times');
assert(html.includes("times[index]||null"),'Use computed estimated times');
assert(html.includes("state.pendingStop"),'Do not use pending preview as actual stop');
assert(manifest.includes('android:icon="@mipmap/ic_launcher"'));
assert(manifest.includes('android:roundIcon="@mipmap/ic_launcher_round"'));
// Validate version metadata without pinning this functional test to one release.
const version=build.match(/versionName\s+['"](\d+)\.(\d+)\.(\d+)['"]/);
assert(version,'Missing semantic Android versionName');
const versionCode=build.match(/versionCode\s+(\d+)/);
assert(versionCode && Number(versionCode[1])>0,'Missing positive Android versionCode');
for(const density of ['mdpi','hdpi','xhdpi','xxhdpi','xxxhdpi'])assert(fs.existsSync(`app/src/main/res/mipmap-${density}/ic_launcher.png`));
assert(fs.existsSync('app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml'));
assert(fs.existsSync('app/src/main/res/drawable/ic_launcher_foreground.png'));
console.log('PASS: stop-based second-by-second late/early/0:00/unknown, midnight, GPS estimated hours, photo mapping untouched');
